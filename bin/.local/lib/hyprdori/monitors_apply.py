def state(data: dict, live: list[dict]) -> dict:
    key, profile = current_profile(data, live, save=False)
    # "enabled" stays the profile's choice; "lid_closed" says clamshell has it off for now
    effective = with_clamshell(profile, live)["monitors"]
    monitors = []
    for m in live:
        mid = ident(m)
        mon = profile["monitors"][mid]
        w, h = logical_size(mon)
        hw = m.get("hardwareDetails") or {}
        monitors.append(
            {
                "id": mid,
                "name": m["name"],
                "description": (m.get("description") or "").strip(),
                "make": m.get("make", ""),
                "model": m.get("model", ""),
                "internal": is_internal(m["name"]),
                "enabled": mon["enabled"],
                "lid_closed": mon["enabled"] and not effective[mid]["enabled"],
                "mode": mon["mode"],
                "modes": available_modes(m) or [mon["mode"]],
                "x": mon["x"],
                "y": mon["y"],
                "width": w,
                "height": h,
                "scale": mon["scale"],
                "transform": mon.get("transform", 0),
                "vrr": mon.get("vrr", 0),
                "cm": mon.get("cm", "srgb") if mon.get("cm") in COLOR_MODES else "srgb",
                "bitdepth": int(mon.get("bitdepth", 10)),
                "max_bitdepth": max_bitdepth(m),
                "vrr_capable": bool(hw.get("vrrCapable")),
            }
        )
    return {
        "key": key,
        "text_size": profile_text_size(profile),
        "primary": profile.get("primary", ""),
        "monitors": monitors,
        "workspaces": profile["workspaces"],
    }


def set_state(data: dict, live: list[dict], new: dict) -> None:
    _key, profile = current_profile(data, live)
    for m in new.get("monitors", []):
        mon = profile["monitors"].get(m["id"])
        if mon is None:
            continue
        for field in (
            "enabled",
            "mode",
            "x",
            "y",
            "scale",
            "transform",
            "vrr",
            "cm",
            "bitdepth",
        ):
            if field in m:
                mon[field] = m[field]
        if mon.get("vrr") not in VRR_MODES:
            mon["vrr"] = 0
        if mon.get("cm") not in COLOR_MODES:
            mon["cm"] = "srgb"
        mon["bitdepth"] = 8 if int(mon.get("bitdepth", 10)) == 8 else 10
        w, h = parse_mode(mon["mode"])
        mon["scale"] = clean_scale(float(mon["scale"]), w, h)
    if not any(mon["enabled"] for mon in profile["monitors"].values()):
        print("refusing to disable every monitor", file=sys.stderr)
        return
    if "primary" in new:
        profile["primary"] = new["primary"]
    if "workspaces" in new:
        profile["workspaces"] = {str(k): v for k, v in new["workspaces"].items() if v}
    if "text_size" in new:
        profile["text_size"] = max(9, min(20, int(new["text_size"])))
    save_profiles(data)
    apply(data, live)


def reset(data: dict, live: list[dict]) -> None:
    """Displays > Defaults: this setup as if it were seen for the first time. Its profile goes,
    Hyprland places the monitors with its own rule (preferred mode, automatic position and
    scale), and a new profile is made from that layout, workspaces split again."""
    data["profiles"].pop(profile_key(live), None)
    save_profiles(data)
    GENERATED_FILE.parent.mkdir(parents=True, exist_ok=True)
    GENERATED_FILE.write_text(
        "-- Generated by ~/.local/bin/hyprdori-monitors: no profile yet\n\n"
        + FALLBACK_RULE
        + "\n"
    )
    if GAMEMODE.exists() and GAMEMODE_SCRIPT.exists():
        run(["bash", str(GAMEMODE_SCRIPT), "normal"])
    run(["hyprctl", "reload"])
    time.sleep(1.0)  # the monitors take their new modes
    apply(data, live_monitors(), force_reload=True)
